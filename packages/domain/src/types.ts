export type Testament = "Old Testament" | "New Testament" | "Deuterocanonical";

export interface Token {
  text: string;
  lexiconEntryIds?: string[];
  // STEP morph codes (eg V-AAI-3S), parallel to lexiconEntryIds
  // TODO: generate the morph code table from STEP TEGMC/TEHMC
  morphCodeIds?: string[];
}

export interface Chapter {
  id: string;
  bookId: string;
  bibleId: string;
  number: number;
  verses: string[];
  chapterRecordKey: string;
}

export interface Verse {
  id: string;
  bibleId: string;
  bookId: string;
  chapterId: string;
  verseNumber: number;
  tokens: Token[];
  verseRecordKey: string;
}

export interface Bible {
  id: string;
  books: string[];
  abbreviation: string;
  name: string;
  language: string;
  description?: string;
}

export interface Book {
  id: string;
  bibleId: string;
  name: string;
  chapters: string[];
  bookRecordKey: string;
}

export interface VerseAudio {
  bibleId: string;
  chapterId: string;
  verseId: string;
  data: Uint8Array;
}

export interface ChapterAudio {
  bibleId: string;
  chapterId: string;
  versesAudio: VerseAudio[];
  chapterRecordKey: string;
}

export interface BibleSource {
  bible?: Bible;
  chapter?: Chapter;
  book?: Book;
  verses?: Verse[];
}

export interface BiblePreset {
  name: string;
  mainBibleId: string;
  glossBibleId: string;
}

export interface Session {
  sessionId: string;
  sessionDate: string;
  visits: {
    main: {
      bibleId: string;
      bibleName: string;
      bookId: string;
      chapterId: string;
    };
    gloss: {
      bibleId: string;
      bibleName: string;
      bookId: string;
      chapterId: string;
    };
    visitedAt: string;
  }[];
}

// Lexicon entries, generated by scripts/lexicons and looked up by the ids
// in Token.lexiconEntryIds

// Languages with Strong's numbers (Greek, Hebrew, Aramaic)
export type StrongsLanguage = "grc" | "hbo" | "arc";

export type LatinLanguage = "lat"

export type Language = StrongsLanguage | "lat";

export type PartOfSpeech =
  | "noun"
  | "verb"
  | "adjective"
  | "adverb"
  | "article"
  | "conjunction"
  | "preposition"
  | "particle"
  | "negative"
  | "interjection"
  | "interrogative"
  | "conditional"
  | "correlative"
  | "pronoun_personal"
  | "pronoun_possessive"
  | "pronoun_reflexive"
  | "pronoun_relative"
  | "pronoun_demonstrative"
  | "pronoun_impersonal";

export type Gender = "masculine" | "feminine" | "neuter" | "common";

export type NameType = "location" | "person" | "gentilic" | "title";

export interface ParsedMorph {
  language: string;
  partOfSpeech?: PartOfSpeech;
  gender?: Gender[];
  nameType?: NameType;
  number?: "singular" | "plural";
}

export interface LexiconEntry {
  id: string;
  language: Language;
  lemma: string;
  transliteration: string;
  gloss: string;
  definition: string;
  morphRaw: string;
  morph: ParsedMorph;
}

// Greek and Hebrew entries, keyed by STEP's Strong's numbers
export type StrongsLexiconEntry = {
  language: StrongsLanguage;
  eStrong: string;
  dStrong: string;
  uStrong: string;
} & LexiconEntry

// Lewis & Short entries, keyed by the L&S key
export type LatinLexiconEntry = {
  language: LatinLanguage;
  entryType: LatinEntryType;
  senses: LatinSense[];
} & LexiconEntry

// Any entry the app looks up; narrow on language, eg language === "lat"
export type AnyLexiconEntry = StrongsLexiconEntry | LatinLexiconEntry;

// main: ordinary entry, greek: word of Greek origin, hapax: attested once,
// gloss: known only from ancient glossaries, foreign: other loanword,
// spur: spurious reading
export type LatinEntryType =
  | "main"
  | "greek"
  | "hapax"
  | "gloss"
  | "foreign"
  | "spur";

export interface LatinSense {
  id: string;
  level: number;
  n: string;
  text: string;
}
